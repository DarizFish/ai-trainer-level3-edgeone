export function rubricIdsFor(task,field){
  let ids;
  if(field.kind==='code') {
    const cell=Number(field.source.cellId.replace('cell-',''));
    ids=[codeCriteria[task.code]?.[cell]?.[field.source.line]];
  }else if(task.group==='4.1'||task.group==='4.2')ids=[1];
  else if(task.group==='3.1')ids=[field.source.section||4];
  else if(task.group==='1.2') {
    const groups=task.code==='1.2.2'?[[1,2,3],[4,5,6],[6]]:[[1,2],[3,4],[5]];
    ids=groups[field.source.section-1];
  }else if(task.group==='2.1')ids=[(task.code==='2.1.5'?9:8)+field.source.section];
  else ids=[reportCriteria[task.code]];
  if(!ids?.length||ids.some(id=>!id||!task.rubric.some(r=>r.id===`M${id}`)))throw new Error(`Unmapped rubric: ${task.code}/${field.id}`);
  return ids.map(id=>`M${id}`);
}
